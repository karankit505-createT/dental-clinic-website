COMMENT ON COLUMN public.appointments.patient_name IS 'Full name of the patient';
COMMENT ON COLUMN public.appointments.age IS 'Age of the patient in years';
COMMENT ON COLUMN public.appointments.gender IS 'Gender of the patient (Male/Female/Other)';
