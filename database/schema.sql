-- --------------------------------------------------------------------
-- 3. INDEXES FOR HIGH-PERFORMANCE QUERYING
-- Accelerates searches by mobile number, appointment date, and doctor ID.
-- --------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_appointments_mobile ON public.appointments(mobile);
CREATE INDEX IF NOT EXISTS idx_appointments_date ON public.appointments(appointment_date);
CREATE INDEX IF NOT EXISTS idx_appointments_doctor ON public.appointments(doctor_id);
CREATE INDEX IF NOT EXISTS idx_doctors_email ON public.doctors(email);


-- --------------------------------------------------------------------
-- 4. ROW-LEVEL SECURITY (RLS) POLICIES
-- Enables anonymous public booking/lookup and doctor updates.
-- --------------------------------------------------------------------

-- Enable RLS on both tables
ALTER TABLE public.doctors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;

-- Allow public read access to doctors list (for booking form dropdown)
CREATE POLICY "Allow public read access to doctors"
ON public.doctors FOR SELECT TO public
USING (true);

-- Allow public users to insert new appointments (booking form submission)
CREATE POLICY "Allow public insert into appointments"
ON public.appointments FOR INSERT TO public
WITH CHECK (true);

-- Allow public users to read appointments (for patient appointment lookup)
CREATE POLICY "Allow public read access to appointments"
ON public.appointments FOR SELECT TO public
USING (true);

-- Allow public / authenticated users to update appointment status (for cancellation & doctor status updates)
CREATE POLICY "Allow public update access to appointments"
ON public.appointments FOR UPDATE TO public
USING (true)
WITH CHECK (true);


-- --------------------------------------------------------------------
-- 5. STORAGE BUCKET FOR PATIENT DOCUMENTS
-- Creates public storage bucket for uploading prescriptions & X-rays.
-- --------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('patient-documents', 'patient-documents', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS Policies: Allow public file uploads, updates and views
DROP POLICY IF EXISTS "Allow public document uploads" ON storage.objects;
DROP POLICY IF EXISTS "Allow public document viewing" ON storage.objects;
DROP POLICY IF EXISTS "Allow public storage uploads" ON storage.objects;
DROP POLICY IF EXISTS "Allow public storage select" ON storage.objects;
DROP POLICY IF EXISTS "Allow public storage update" ON storage.objects;

CREATE POLICY "Allow public storage uploads"
ON storage.objects FOR INSERT TO public
WITH CHECK (bucket_id = 'patient-documents');

CREATE POLICY "Allow public storage update"
ON storage.objects FOR UPDATE TO public
USING (bucket_id = 'patient-documents')
WITH CHECK (bucket_id = 'patient-documents');

CREATE POLICY "Allow public storage select"
ON storage.objects FOR SELECT TO public
USING (bucket_id = 'patient-documents');


