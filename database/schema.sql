-- --------------------------------------------------------------------
-- 1. DOCTORS TABLE
-- Stores doctor profiles, specializations, email & auth linkages.
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.doctors (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    specialization TEXT,
    email TEXT UNIQUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Comments on doctors table columns
COMMENT ON TABLE public.doctors IS 'Stores registered clinic doctors and specializations';
COMMENT ON COLUMN public.doctors.id IS 'Unique identifier for the doctor';
COMMENT ON COLUMN public.doctors.name IS 'Full name of the doctor (e.g., Dr. Rajesh Kumar)';
COMMENT ON COLUMN public.doctors.specialization IS 'Area of dental expertise (e.g., Orthodontist, Endodontist)';
COMMENT ON COLUMN public.doctors.email IS 'Doctor email address used for portal login authentication';


-- --------------------------------------------------------------------
-- 2. APPOINTMENTS TABLE
-- Stores patient booking details, assigned doctor, status & document URL.
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name TEXT NOT NULL,
    age INT NOT NULL,
    gender TEXT,
    email TEXT,
    mobile TEXT NOT NULL,
    issue TEXT NOT NULL,
    document_url TEXT,
    doctor_report_url TEXT,
    diagnosis TEXT,
    medicine TEXT,
    next_visit_date DATE,
    appointment_date DATE NOT NULL,
    appointment_time TEXT NOT NULL,
    doctor_id UUID REFERENCES public.doctors(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

